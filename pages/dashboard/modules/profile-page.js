/**
 * User Profile Page - browse and edit LivingMemory user profiles.
 *
 * 页面数据来自 Page API（宿主插件 API 是静态路由，path 参数走 query/body）：
 *   GET    profiles?scope&persona_id            列表；两者都给时返回单条 data.profile
 *   GET    profiles/detail?id=<id>              详情（含 pending）
 *   GET    profiles/history?id=<id>&limit=20
 *   GET    profiles/pending?scope&persona_id
 *   POST   profiles/update        {id, profile} 保存 → data.profile
 *   POST   profiles/delete        {id}          删除 → data.deleted
 *   POST   profiles/pending/resolve {scope, persona_id, index, action}
 *
 * 页面本身不直接操作后端存储；所有编辑都在草稿里进行，保存时整份 profile 提交。
 */

